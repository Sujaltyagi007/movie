let displayNames: Intl.DisplayNames | null = null;
let regionNames: Intl.DisplayNames | null = null;

function isLanguageCode(code: string) {
  try {
    displayNames ??= new Intl.DisplayNames(["en"], { type: "language", fallback: "none" });
    return displayNames.of(code) !== undefined;
  } catch {
    return false;
  }
}

function isRegionCode(code: string) {
  try {
    regionNames ??= new Intl.DisplayNames(["en"], { type: "region", fallback: "none" });
    return regionNames.of(code.toUpperCase()) !== undefined;
  } catch {
    return false;
  }
}

export function languageLabel(code: string) {
  if (!code) return "Original";
  try {
    const english = new Intl.DisplayNames(["en"], { type: "language" }).of(code) ?? code;
    const native = new Intl.DisplayNames([code], { type: "language" }).of(code) ?? english;
    const nativeCap = native.charAt(0).toLocaleUpperCase(code) + native.slice(1);
    return nativeCap === english ? english : `${nativeCap} · ${english}`;
  } catch {
    return code.toUpperCase();
  }
}

const strip = (s: string) => s.normalize("NFKD").replace(/[̀-ͯ]/g, "").toLowerCase();

export function normalizeLanguage(value: unknown): string {
  const raw = Array.isArray(value) ? value[0] : value;
  if (typeof raw !== "string") return "";
  const v = strip(raw.trim());
  if (!v) return "";
  if (NAMES[v]) return NAMES[v];
  if (THREE_LETTER[v]) return THREE_LETTER[v];
  const m = v.match(/^([a-z]{2})(?:[-_]([a-z]{2}))?$/);
  if (m && isLanguageCode(m[1])) return m[2] ? `${m[1]}-${m[2].toUpperCase()}` : m[1];
  return "";
}

const AUTO_TOKENS = new Set(["asr", "autogenerated", "auto"]);
const NOISE_TOKENS = new Set(["512kb", "ia", "hd", "sd", "720p", "1080p", "480p", "360p", "4k", "h264", "mpeg4", "final", "c"]);

export function languageFromFileName(fileName: string): { language: string; auto: boolean; stem: string } {
  const base = fileName.split("/").pop() ?? fileName;
  const withoutExt = base.replace(/\.[a-z0-9]{2,4}$/i, "");
  const tokens = withoutExt.split(/[._\s\-()[\]{}]+/).filter(Boolean);
  let auto = false;
  let language = "";
  let cut = tokens.length;
  for (let i = tokens.length - 1; i >= Math.max(0, tokens.length - 4); i--) {
    const t = strip(tokens[i]);
    if (AUTO_TOKENS.has(t)) { auto = true; cut = i; continue; }
    if (NOISE_TOKENS.has(t)) { cut = i; continue; }
    if (!language) {
      const prev = i > 0 ? strip(tokens[i - 1]) : "";
      if (i === tokens.length - 1 && /^[a-z]{2}$/.test(t) && /^[a-z]{2}$/.test(prev) && isLanguageCode(prev) && isRegionCode(t) && prev !== t) {
        language = `${prev}-${t.toUpperCase()}`; cut = i - 1; i--; continue;
      }
      const code = NAMES[t] ?? THREE_LETTER[t] ?? (/^[a-z]{2}$/.test(t) && isLanguageCode(t) && (tokens.length === 1 || i === tokens.length - 1 || auto) ? t : "");
      if (code) { language = code; cut = i; continue; }
    }
    break;
  }
  const stem = strip(tokens.slice(0, cut).join(" "));
  return { language, auto, stem };
}

export function videoStem(fileName: string) {
  return languageFromFileName(fileName).stem;
}
